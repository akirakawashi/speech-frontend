/**
 * Что в черновике настроек отличается от пришедшего с сервера.
 *
 * `PUT /admin/settings` принимает **набор изменений**, а не состояние формы.
 * Разница существенная: «изменено» на экране означает «в базе есть строка для
 * этого ключа», и форма, отправлявшая все восемь значений целиком, после
 * первого же сохранения помечала изменёнными все восемь — включая те, которых
 * никто не трогал. Пометка переставала что-либо значить ровно тогда, когда она
 * нужна: при разборе «почему система ведёт себя не так».
 *
 * Отдельным модулем, а не рядом со страницей: Next.js не разрешает странице
 * экспортировать ничего, кроме своего умолчания и известного ему набора имён, —
 * а проверять эту функцию хочется отдельно от экрана.
 */

export type SettingsValues = Record<string, unknown>;

/**
 * Находит значения черновика, которые отличаются от пришедших с сервера.
 *
 * Сравнение по JSON, а не по ссылке: `max_attempts` — вложенный объект, и после
 * правки одного этапа он в любом случае новый объект, хотя по содержимому мог
 * не измениться.
 *
 * Пустой результат означает «менять нечего». Отправлять такой запрос не надо:
 * сервер ответит отказом `nothing_to_change`, и человек получит сообщение об
 * ошибке за то, что ничего не менял.
 *
 * @param draft Значения формы.
 * @param server Значения с сервера.
 * @returns Только изменённые значения; пустой объект — менять нечего.
 */
export function changedValues(draft: SettingsValues, server: SettingsValues): SettingsValues {
  const result: SettingsValues = {};
  for (const [key, value] of Object.entries(draft)) {
    if (JSON.stringify(value) !== JSON.stringify(server[key])) result[key] = value;
  }
  return result;
}
